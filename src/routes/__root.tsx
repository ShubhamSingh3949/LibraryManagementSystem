function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="en">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function AuthGuard({ children }: { children: ReactNode }) {
  const { session, isLoading } = useAuth();
  const router = useRouter();

  useEffect(() => {
    if (!isLoading && !session && router.state.location.pathname !== "/login") {
      router.navigate({ to: "/login" });
    }
  }, [session, isLoading, router.state.location.pathname]);

  if (isLoading) return null;

  if (!session && router.state.location.pathname !== "/login") {
    return null;
  }

  return <>{children}</>;
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();
  const router = useRouter();
  const isLogin = router.state.location.pathname === "/login";

  return (
    <QueryClientProvider client={queryClient}>
      <AuthProvider>
        <AuthGuard>
          {isLogin ? (
            <>
              <Outlet />
              <Toaster position="top-right" richColors />
            </>
          ) : (
            <StoreProvider>
              <ActionsProvider>
                <AppShell>
                  {/* Required: nested routes render here. */}
                  <Outlet />
                </AppShell>
                <Toaster position="top-right" richColors />
              </ActionsProvider>
            </StoreProvider>
          )}
        </AuthGuard>
      </AuthProvider>
    </QueryClientProvider>
  );
}
